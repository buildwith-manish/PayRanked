#!/usr/bin/env python3
"""
Writes review/VO-CUES.md: the cue sheet for recording the voice-over. Every time is the master clock of the current cut,
read from scripts/timing.json (which comes from the video's own timeline), so the sheet and the video cannot disagree.

    npm run vo-cues
"""
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
TM = json.load(open(os.path.join(ROOT, 'scripts', 'timing.json')))
STATES = {s['name']: s['rpp'] for s in json.load(open(os.path.join(ROOT, 'src', 'data', 'states.json')))}
S = TM['shots']


def mmss(t):
    return f'{int(t // 60)}:{t % 60:04.1f}'


out = ['# Voice-over cue sheet', '',
       f"Generated by `npm run vo-cues` from `scripts/timing.json`. Master clock, current cut: **{mmss(TM['total'])}**.",
       '`public/vo.wav` is one file that starts at 0:00 of the video. Then run `npm run vo-envelope` and set `vo: true` in',
       '`src/audio/config.ts`. Re-run this after any cut: the times below move with the timeline.', '',
       '## Sections', '', '| Section | Start | End | Length |', '|---|---|---|---|']
names = {'shot1': 'Cold open', 'shot2': 'Intro (own sound, no voice)', 'shot3': 'Method', 'countdown': 'Countdown', 'shot5': 'Reality check', 'shot6': 'Outro'}
for k, v in S.items():
    out.append(f"| {names[k]} | {mmss(v['start'])} | {mmss(v['start'] + v['dur'])} | {v['dur']:.1f} s |")

def beats(title, start, d):
    out.extend(['', f'## {title}', '', '| Time | Beat |', '|---|---|'])
    for k, v in d.items():
        out.append(f'| {mmss(start + v)} | {k} |')

beats('Cold open beats', S['shot1']['start'], TM['shot1'])
beats('Method beats', S['shot3']['start'], TM['shot3'])

c = S['countdown']['start']
out.extend(['', '## Countdown', '',
            'Each reveal: the rank slams, the camera flies in, the name appears, the BEA score, the dollars, then the row locks into the rail.',
            '#1 is a near-tie with #2 and is framed as the top tier ("ranked by index"), not as an outright winner: keep the line',
            'about it honest (about $130 apart, inside the margin of the data).', '',
            '| Reveal | Start | Name | BEA score | Dollars | Locks | Ends |', '|---|---|---|---|---|---|---|'])
rows = [(r['from'], f"{r['label']} {' + '.join(r['names'])}", r) for r in TM['reveals']] + [(b['from'], f"Break: {b['kind']}", b) for b in TM['breaks']]
for _, label, r in sorted(rows, key=lambda x: x[0]):
    a = c + r['from']
    if 'name' in r:
        out.append(f"| {label} | {mmss(a)} | {mmss(a + r['name'])} | {mmss(a + r['bea'])} | {mmss(a + r['dollars'])} | {mmss(a + r['lock'])} | {mmss(a + r['dur'])} |")
    else:
        out.append(f"| {label} | {mmss(a)} | | | | | {mmss(a + r['dur'])} |")

beats('Reality check beats', S['shot5']['start'], TM['shot5'])
beats('Outro beats', S['shot6']['start'], TM['shot6'])
out.append('')
os.makedirs(os.path.join(ROOT, 'review'), exist_ok=True)
open(os.path.join(ROOT, 'review', 'VO-CUES.md'), 'w').write('\n'.join(out))
print('review/VO-CUES.md')
